#!/usr/bin/env python3
"""Bundle site/funding/data/*.json into site/funding/programs.js.

The funding finder ships its program list as a script, not a fetch: the page
runs under connect-src 'none', so it cannot make a network request at all, and
that is the proof behind "we collect nothing". The bundle is checked in;
tests/test_funding.py fails when it drifts from the data files.

Run it after editing any data file:
    python tools/build_funding_data.py
"""

from __future__ import annotations

import datetime as dt
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_funding_data import DATA, check_all, load  # noqa: E402

OUT = os.path.join(os.path.dirname(DATA), "programs.js")


def bundle(records: list[dict]) -> str:
    built = max((r["checked"] for r in records), default="")
    body = json.dumps(sorted(records, key=lambda r: r["id"]), ensure_ascii=False, indent=1)
    return (
        "// Generated by tools/build_funding_data.py from site/funding/data. Do not edit.\n"
        f"window.FUNDING_BUILT = {json.dumps(built)};\n"
        f"window.FUNDING_PROGRAMS = {body};\n"
    )


def main() -> int:
    records, errs = load(DATA)
    errs += check_all(records, dt.date.today())
    if errs:
        print("\n".join(errs))
        print("not built: fix the data first")
        return 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(bundle(records))
    print(f"wrote {OUT}: {len(records)} programs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
